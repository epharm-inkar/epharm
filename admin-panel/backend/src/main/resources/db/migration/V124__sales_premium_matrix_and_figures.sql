-- V124: the daily collector of the sales premium (26.11.2026). The server now computes the premium itself from the
-- central Standard-N database, so it needs the matrix of the month (which products pay how much per pack) and a place
-- to keep each seller's latest packs for the statement. Nothing here moves money: the wallet, the ledger and the
-- pending table are those of V123.

-- 1. The matrix of a month: one row per product (Standard-N WARES.ID, GUID in upper case) and the bonus per pack in
--    tenge. A product that pays nothing has a zero bonus and is still read, so its packs are counted. A month's matrix
--    is replaced as a whole by the upload endpoint; the figures of the month are recomputed from the 1st with it.
CREATE TABLE sales_premium_matrix (
    period         VARCHAR(7)    NOT NULL CHECK (period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    ware_id        VARCHAR(36)   NOT NULL CHECK (ware_id ~ '^[0-9A-F]{8}(-[0-9A-F]{4}){3}-[0-9A-F]{12}$'),
    name           VARCHAR(255)  NOT NULL DEFAULT '',
    bonus_per_pack NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (bonus_per_pack >= 0 AND bonus_per_pack <= 100000),
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    PRIMARY KEY (period, ware_id)
);

-- 2. The latest cumulative figure the source reported per seller and month, whether the seller is credited or waits:
--    the packs (the ledger holds only tenge) and the amount. Written by every real import, read by the statement.
--    The IIN is as sensitive as in sales_premium_pending; there is no name or phone here.
CREATE TABLE sales_premium_figures (
    iin        VARCHAR(12) NOT NULL CHECK (iin ~ '^[0-9]{12}$'),
    period     VARCHAR(7)  NOT NULL CHECK (period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    packs      NUMERIC(14,3) CHECK (packs IS NULL OR packs >= 0),
    amount_kzt BIGINT      NOT NULL CHECK (amount_kzt >= 0),
    through    DATE        NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (period, iin)
);

